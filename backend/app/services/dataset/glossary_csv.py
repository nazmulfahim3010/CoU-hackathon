"""Validator for the Sylheti glossary CSV (the controlled lexical resource used during normalization).

Read-only: the source CSV is never modified. The runtime glossary (app/data/dialects/sylheti.json, generated by
scripts/import_glossary.py) is checked against it so the two cannot silently drift apart.
"""
from __future__ import annotations

import csv
import io
import os
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, get_args

from app.schemas.glossary import GlossaryCategory
from app.services.dataset.sylheti_audio_dataset import REPO_ROOT, ValidationIssue

DEFAULT_GLOSSARY_CSV = REPO_ROOT / "data" / "glossary" / "sylheti_glossary_120-final.csv"
REQUIRED_COLUMNS = (
    "id", "regional_expression", "standard_bangla", "english_meaning", "dialect", "category", "example_sentence",
    "source", "contributor", "verification_status", "verified_by", "verification_date", "verification_note",
)
VALID_CATEGORIES = set(get_args(GlossaryCategory))
VALID_STATUS = {"verified", "unverified"}


def glossary_csv_path() -> Path:
    env = os.environ.get("KOTHA_GLOSSARY_CSV")
    return Path(env) if env else DEFAULT_GLOSSARY_CSV


def _has_bengali(text: str) -> bool:
    return any("ঀ" <= ch <= "৿" for ch in text)


@dataclass
class GlossaryCsvLoad:
    path: Path
    entries: list[dict[str, str]] = field(default_factory=list)
    issues: list[ValidationIssue] = field(default_factory=list)

    @property
    def errors(self) -> list[ValidationIssue]:
        return [i for i in self.issues if i.severity == "error"]

    def summary(self) -> dict[str, Any]:
        from collections import Counter

        return {
            "entries_loaded": len(self.entries),
            "unique_ids": len({e["id"] for e in self.entries}),
            "unique_expressions": len({unicodedata.normalize("NFC", e["regional_expression"]) for e in self.entries}),
            "dialects": dict(Counter(e["dialect"] for e in self.entries)),
            "categories": dict(Counter(e["category"] for e in self.entries)),
            "verification_status": dict(Counter(e["verification_status"] for e in self.entries)),
            "verifiers": dict(Counter(e["verified_by"] for e in self.entries)),
            "invalid_entries": len({i.recording_id for i in self.errors if i.recording_id}),
            "errors": len(self.errors),
            "warnings": len(self.issues) - len(self.errors),
        }


def load_glossary_csv(path: Path | None = None) -> GlossaryCsvLoad:
    path = Path(path) if path else glossary_csv_path()
    out = GlossaryCsvLoad(path)
    if not path.exists():
        out.issues.append(ValidationIssue("error", "GLOSSARY_NOT_FOUND", "Glossary CSV not found."))
        return out
    try:
        text = path.read_text(encoding="utf-8-sig")
    except (OSError, UnicodeDecodeError) as exc:
        out.issues.append(ValidationIssue("error", "GLOSSARY_UNREADABLE", f"Cannot read glossary CSV ({type(exc).__name__})."))
        return out
    reader = csv.DictReader(io.StringIO(text))
    missing = [c for c in REQUIRED_COLUMNS if c not in (reader.fieldnames or [])]
    if missing:
        out.issues.append(ValidationIssue("error", "GLOSSARY_MISSING_COLUMNS", f"Missing columns: {', '.join(missing)}"))
        return out

    seen_ids: set[str] = set()
    seen_expr: dict[str, str] = {}
    for line_no, row in enumerate(reader, start=2):
        eid = (row.get("id") or "").strip() or f"line{line_no}"
        entry = {c: (row.get(c) or "").strip() for c in REQUIRED_COLUMNS}  # keep values verbatim apart from edge spaces
        bad = False

        def err(code: str, msg: str) -> None:
            nonlocal bad
            bad = True
            out.issues.append(ValidationIssue("error", code, msg, eid))

        if None in row or any(v is None for v in row.values()):
            err("GLOSSARY_ROW_SHAPE", "Row has the wrong number of columns.")
        for col in ("id", "regional_expression", "standard_bangla", "english_meaning", "dialect", "category", "verification_status"):
            if not entry[col]:
                err("GLOSSARY_MISSING_VALUE", f"Required value '{col}' is empty.")
        if entry["id"] in seen_ids:
            err("GLOSSARY_DUPLICATE_ID", "Duplicate glossary id.")
        seen_ids.add(entry["id"])
        norm = unicodedata.normalize("NFC", entry["regional_expression"])
        if norm in seen_expr:
            err("GLOSSARY_DUPLICATE_EXPRESSION", f"Expression already used by {seen_expr[norm]}.")
        seen_expr.setdefault(norm, entry["id"])
        if entry["regional_expression"] and not (_has_bengali(entry["regional_expression"]) or any(c.isdigit() for c in entry["regional_expression"])):
            err("GLOSSARY_NOT_BENGALI", "Regional expression contains no Bengali script.")
        if entry["regional_expression"] != norm:
            out.issues.append(ValidationIssue("warning", "GLOSSARY_NOT_NFC", "Expression is not NFC-normalised.", eid))
        if entry["dialect"] and entry["dialect"] != "sylheti":
            err("GLOSSARY_DIALECT", f"Unexpected dialect '{entry['dialect']}'.")
        if entry["category"] and entry["category"] not in VALID_CATEGORIES:
            err("GLOSSARY_CATEGORY", f"Unknown category '{entry['category']}'.")
        if entry["verification_status"] and entry["verification_status"] not in VALID_STATUS:
            err("GLOSSARY_STATUS", f"Unknown verification_status '{entry['verification_status']}'.")
        if entry["verification_status"] == "verified" and not (entry["verified_by"] and entry["verification_date"]):
            out.issues.append(ValidationIssue("warning", "GLOSSARY_VERIFICATION_METADATA", "Verified entry lacks verifier or date.", eid))
        if not bad:
            out.entries.append(entry)
    return out


def compare_with_runtime(csv_entries: list[dict[str, str]], runtime_entries: list[dict[str, Any]]) -> list[ValidationIssue]:
    """Detect drift between the source CSV and the runtime JSON the normalizer actually uses."""
    issues: list[ValidationIssue] = []
    rt = {e["id"]: e for e in runtime_entries}
    for e in csv_entries:
        r = rt.get(e["id"])
        if r is None:
            issues.append(ValidationIssue("error", "RUNTIME_MISSING_ENTRY", "CSV entry missing from runtime glossary.", e["id"]))
            continue
        pairs = [
            ("regional_expression", "regional_expression"), ("standard_bangla", "standard_bangla"),
            ("verification_status", "verification_status"), ("verified_by", "verified_by"),
            ("verification_date", "verification_date"), ("verification_note", "verification_note"),
            ("category", "category"), ("example_sentence", "example_sentence"),
        ]
        for csv_key, rt_key in pairs:
            if (r.get(rt_key) or "") != e[csv_key]:
                issues.append(ValidationIssue("error", "RUNTIME_MISMATCH", f"Runtime '{rt_key}' differs from the source CSV.", e["id"]))
    for extra in set(rt) - {e["id"] for e in csv_entries}:
        issues.append(ValidationIssue("error", "RUNTIME_EXTRA_ENTRY", "Runtime glossary has an entry not in the CSV.", extra))
    return issues
