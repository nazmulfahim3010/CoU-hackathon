from fastapi import APIRouter, Depends

from app.api.deps import get_sessions
from app.config import Settings, get_settings
from app.core.exceptions import KothaError
from app.core.logging import get_logger
from app.core.session_manager import SessionManager, Stage
from app.schemas.clinical import ClinicalExtraction, ExtractionRequest, ExtractionResponse
from app.services import clinical_extractor, demo_data
from app.services.grounding import ground_extraction
from app.services.llm_provider import llm_configured

log = get_logger("extraction")

router = APIRouter(prefix="/api/clinical", tags=["extraction"])


@router.post("/extract", response_model=ExtractionResponse)
async def extract(
    req: ExtractionRequest,
    s: Settings = Depends(get_settings),
    sessions: SessionManager = Depends(get_sessions),
):
    session = sessions.require(req.session_id, Stage.CONFIRMED)
    confirmed = session.data["confirmed"]
    if session.mode == "demo":
        extraction = None
        # Try real LLM extraction pipeline first if LLM provider is configured
        if llm_configured(s):
            try:
                extraction = await clinical_extractor.extract(confirmed, s)
                source, provider = "llm", s.llm_provider
                note = "DEMO: Live LLM extraction ran on this prepared demo sample."
            except Exception:
                extraction = None

        if extraction is None:
            # Fall back to cached demo output ONLY when LLM provider is unconfigured or fails
            cached = demo_data.get_cached_output(session.demo_scenario_id or "")
            cached_extraction = cached.get("extraction")
            scenario = demo_data.get_scenario(session.demo_scenario_id or "")
            expected_norm = scenario.get("normalized")
            cached_norm = cached.get("normalization", {}).get("normalized")
            if confirmed != expected_norm and confirmed != cached_norm:
                raise KothaError(
                    409,
                    "DEMO_TEXT_EDITED",
                    "ক্যাশড ডেমো আউটপুট শুধুমাত্র অপরিবর্তিত নমুনা পাঠ্যের জন্য প্রযোজ্য। এডিট করা পাঠ্য প্রক্রিয়াকরণের জন্য অনুগ্রহ করে LLM API Key কনফিগার করে লাইভ মোড ব্যবহার করুন। (Cached demo output only matches the unedited sample text. Switch to live mode or configure LLM to process edited text.)",
                )
            extraction = ClinicalExtraction.model_validate(cached_extraction or scenario["extraction"])
            source, provider = "cached_demo_output", "cached_demo_output"
            note = "cached demo output: LLM provider unavailable; pre-saved sample / unverified demo extraction shown."
    else:
        # LIVE MODE: NEVER reads cached outputs!
        extraction = await clinical_extractor.extract(confirmed, s)
        source, provider = "llm", s.llm_provider
        note = "Generated by an LLM from the confirmed text only. Verify against the patient statement."
    extraction = ground_extraction(extraction, confirmed)  # idempotent; also covers cached/demo outputs
    session.data["extraction"] = extraction
    session.data["extraction_source"] = source
    session.stage = max(session.stage, Stage.EXTRACTED)
    return ExtractionResponse(
        session_id=session.id,
        source=source,
        provider=provider,
        extraction=extraction,
        note=note,
        mode=session.mode,
    )
